import { ref } from 'vue'
/**
 * Ключ идемпотентности на одно намерение пользователя.
 *
 * Контур требует заголовок при создании инвойса и заявки на вывод и помнит ключ
 * сутки. Смысл ключа — в том, чтобы **повтор** попал в тот же ключ: если ответ
 * потерялся по дороге, вторая отправка не должна создавать второй инвойс.
 *
 * Поэтому ключ живёт от открытия формы до успеха, а не от вызова к вызову.
 * Свежий UUID на каждый `fetch` формально контракт соблюдает, но защиты не даёт
 * никакой: два запроса с разными ключами — это два разных объекта.
 *
 * После успеха ключ сбрасывается: следующая заявка — новое намерение.
 */
export const useIdempotencyKey = () => {
  const key = ref('')

  /** Ключ текущей попытки. Создаётся при первом обращении, дальше переиспользуется. */
  const current = (): string => {
    if (!key.value) key.value = crypto.randomUUID()
    return key.value
  }

  /** Намерение исполнено — следующая отправка получит свой ключ. */
  const reset = (): void => {
    key.value = ''
  }

  return { current, reset }
}
